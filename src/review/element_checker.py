from __future__ import annotations

import re
from typing import Any


class ElementChecker:
    def __init__(self) -> None:
        self.rules: dict[str, list[tuple[str, str, str]]] = {
            "会议新闻": [
                ("时间", r"(\d{1,2}月\d{1,2}日|上午|下午|近日|日前)", "建议补充会议发生时间。"),
                ("地点", r"(在.{0,20}(召开|举行)|会议室|报告厅|中心)", "建议补充会议地点。"),
                ("会议名称或活动名称", r"(会议|交流会|研讨会|推进会|座谈会)", "建议补充会议名称。"),
                ("参与对象", r"(师生|同学|教师|干部|代表|专家)", "建议补充参会对象。"),
                ("主办/承办单位", r"(主办|承办|协办|由.+?主办)", "建议补充主办或承办单位。"),
                ("出席人员或嘉宾", r"(出席|参加|参会|嘉宾|与会)", "建议补充出席人员信息。"),
                ("讲话/交流内容", r"(指出|强调|表示|介绍|交流|分享)", "建议增加会议交流或讲话内容。"),
                ("总结意义或后续安排", r"(总结|下一步|后续|展望|部署)", "建议补充总结意义或后续安排。"),
                ("审核人", r"(审核[:：]|审核人|审稿)", "建议补充审核人信息。"),
            ],
            "活动纪实": [
                ("时间", r"(\d{1,2}月\d{1,2}日|上午|下午|近日|日前)", "建议补充活动时间。"),
                ("地点", r"(在.{0,20}(开展|举行)|广场|中心|场馆|教室)", "建议补充活动地点。"),
                ("活动名称", r"(活动|实践|比赛|志愿服务|文化节)", "建议补充活动名称。"),
                ("参与对象", r"(学生|教师|志愿者|参与者|同学)", "建议补充参与对象。"),
                ("活动流程", r"(首先|随后|然后|最后|环节|流程)", "建议补充活动流程。"),
                ("现场描写", r"(现场|气氛|热烈|认真|踊跃)", "建议增加现场描写。"),
                ("活动结果或成效", r"(取得|成效|收获|成果|提升)", "建议补充活动结果或成效。"),
                ("审核人", r"(审核[:：]|审核人|审稿)", "建议补充审核人信息。"),
            ],
            "科研成果": [
                ("研究团队", r"(团队|课题组|研究组|实验室)", "建议补充研究团队信息。"),
                ("成果名称", r"(成果|论文|研究|项目)", "建议补充成果名称。"),
                ("发表期刊/会议/项目来源", r"(发表于|期刊|会议|基金|项目)", "建议补充发表或项目来源。"),
                ("研究背景", r"(背景|针对|围绕|面向)", "建议补充研究背景。"),
                ("创新点", r"(首次|创新|突破|提出)", "建议补充创新点。"),
                ("应用价值", r"(应用|推广|价值|前景)", "建议补充应用价值。"),
                ("单位归属", r"(华中农业大学|学院|实验室|单位)", "建议补充单位归属。"),
                ("审核人", r"(审核[:：]|审核人|审稿)", "建议补充审核人信息。"),
            ],
        }

    def check(self, text: str, article_type: str) -> dict[str, Any]:
        rules = self.rules.get(article_type, self.rules["会议新闻"])
        checks = []
        passed = 0
        for element, pattern, suggestion in rules:
            m = re.search(pattern, text)
            ok = bool(m)
            if ok:
                passed += 1
            checks.append(
                {
                    "element": element,
                    "passed": ok,
                    "evidence": m.group(0) if m else "",
                    "suggestion": "" if ok else suggestion,
                }
            )
        total = len(checks)
        failed = total - passed
        return {
            "article_type": article_type,
            "checks": checks,
            "summary": {
                "total": total,
                "passed": passed,
                "failed": failed,
                "pass_rate": round(passed / total, 2) if total else 0.0,
            },
        }
